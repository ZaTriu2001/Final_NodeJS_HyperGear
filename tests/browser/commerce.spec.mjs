import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';
async function fitsViewport(page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
}
test('storefront, responsive menu, filters and pagination', async ({ page }, testInfo) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('link', { name: 'HyperGear - Trang chủ' })).toBeVisible();
  await expect(page.locator('.product-card').first()).toBeVisible();
  await fitsViewport(page);
  await page.screenshot({ path: testInfo.outputPath('home.png'), fullPage: true });
  if (testInfo.project.name === 'mobile') await page.getByRole('button', { name: 'Mở menu' }).click();
  await page.locator('header').getByRole('link', { name: 'Sản phẩm', exact: true }).click();
  await expect(page.locator('.product-card')).toHaveCount(12);
  await page.getByRole('button', { name: '2', exact: true }).click();
  await expect(page).toHaveURL(/page=2/);
  await page.getByLabel('Danh mục', { exact: true }).selectOption('CPU');
  await page.getByLabel('Sắp xếp', { exact: true }).selectOption('price-asc');
  await expect(page).toHaveURL(/category=CPU/);
  await expect(page.locator('.product-card').first()).toBeVisible();
  await fitsViewport(page);
  await page.screenshot({ path: testInfo.outputPath('catalog.png'), fullPage: true });
  expect(errors).toEqual([]);
});
test('guest cart → registration → checkout → order persists after reload', async ({ page }, testInfo) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/san-pham?category=CPU');
  await page.locator('.product-name').first().click();
  await expect(page.locator('.thumb-row img')).toHaveCount(3);
  await page.getByRole('button', { name: 'Thêm vào giỏ hàng', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Đã cập nhật giỏ hàng');
  await page.goto('/thanh-toan');
  await expect(page.getByRole('heading', { name: 'Đăng nhập để hoàn tất mua hàng' })).toBeVisible();
  await page.getByRole('link', { name: 'Tạo tài khoản', exact: true }).click();
  await page.getByLabel('Email', { exact: true }).fill('e2e-' + randomUUID() + '@example.com');
  await page.getByLabel('Họ và tên', { exact: true }).fill('HyperGear E2E');
  await page.getByLabel('Số điện thoại tài khoản', { exact: true }).fill('0901234567');
  await page.getByLabel('Người nhận', { exact: true }).fill('HyperGear E2E');
  await page.getByLabel('Số điện thoại', { exact: true }).fill('0901234567');
  await page.getByLabel('Số nhà / đường', { exact: true }).fill('123 Demo');
  await page.getByLabel('Phường / xã', { exact: true }).fill('Phường Demo');
  await page.getByLabel('Mật khẩu', { exact: true }).fill('DemoTest@2026');
  await page.getByLabel('Xác nhận mật khẩu', { exact: true }).fill('DemoTest@2026');
  await fitsViewport(page);
  await page.getByRole('button', { name: 'Tạo tài khoản', exact: true }).click();
  await expect(page).toHaveURL(/\/thanh-toan$/);
  await page.getByRole('button', { name: 'Tiếp tục', exact: true }).click();
  await page.getByRole('button', { name: 'Xem lại đơn hàng', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Kiểm tra trước khi thanh toán' })).toBeVisible();
  await fitsViewport(page);
  await page.screenshot({ path: testInfo.outputPath('checkout.png'), fullPage: true });
  await page.getByRole('button', { name: 'Thanh toán mô phỏng', exact: true }).click();
  await expect(page).toHaveURL(/\/don-hang\/[a-f0-9]{24}\?success=1/);
  await page.reload();
  await expect(page.getByText('Thanh toán: Đã thanh toán mô phỏng', { exact: true })).toBeVisible();
  await fitsViewport(page);
  await page.screenshot({ path: testInfo.outputPath('order.png'), fullPage: true });
  expect(errors).toEqual([]);
});
